
-- =========================================
-- 1. TABLE UTILISATEUR
-- =========================================

CREATE TABLE UTILISATEUR (
    ID_UTILISATEUR NUMBER(10) PRIMARY KEY,
    NOM VARCHAR2(50) NOT NULL,
    PRENOM VARCHAR2(50),
    EMAIL VARCHAR2(100) NOT NULL UNIQUE,
    MOT_DE_PASSE VARCHAR2(255) NOT NULL,
    TELEPHONE VARCHAR2(20),
    ROLE VARCHAR2(20) NOT NULL,
    DATE_CREATION DATE DEFAULT SYSDATE,

    CONSTRAINT CK_USER_ROLE
    CHECK (ROLE IN ('CLIENT', 'RESTAURATEUR'))
);


-- =========================================
-- 2. TABLE RESTAURANT
-- =========================================

CREATE TABLE RESTAURANT (
    ID_RESTAURANT NUMBER(10) PRIMARY KEY,
    NOM VARCHAR2(100) NOT NULL,
    DESCRIPTION VARCHAR2(500),
    ADRESSE VARCHAR2(200) NOT NULL,
    TELEPHONE VARCHAR2(20),
    ID_RESTAURATEUR NUMBER(10) NOT NULL,

    CONSTRAINT FK_REST_USER
    FOREIGN KEY (ID_RESTAURATEUR)
    REFERENCES UTILISATEUR(ID_UTILISATEUR),

    CONSTRAINT UQ_RESTAURATEUR
    UNIQUE (ID_RESTAURATEUR)
);


-- =========================================
-- 3. TABLE PRODUIT
-- =========================================

CREATE TABLE PRODUIT (
    ID_PRODUIT NUMBER(10) PRIMARY KEY,
    NOM VARCHAR2(100) NOT NULL,
    DESCRIPTION VARCHAR2(500),
    PRIX NUMBER(10,2) NOT NULL,
    IMAGE VARCHAR2(255),
    ID_RESTAURANT NUMBER(10) NOT NULL,

    CONSTRAINT CK_PRODUIT_PRIX
    CHECK (PRIX >= 0),

    CONSTRAINT FK_PROD_CAT
    FOREIGN KEY (ID_RESTAURANT)
    REFERENCES RESTAURANT(ID_RESTAURANT)
);


-- =========================================
-- 4. TABLE MENU
-- =========================================
CREATE TABLE MENU (
    ID_MENU NUMBER(10) PRIMARY KEY,
    NOM VARCHAR2(100) NOT NULL,
    DESCRIPTION VARCHAR2(500),
    DATE_CREATION DATE DEFAULT SYSDATE,
    ID_RESTAURANT NUMBER(10) NOT NULL,

    CONSTRAINT CK_MENU_ACTIF
    CHECK (ACTIF IN (0, 1)),

    CONSTRAINT FK_MENU_RESTAURANT
    FOREIGN KEY (ID_RESTAURANT)
    REFERENCES RESTAURANT(ID_RESTAURANT)
);
