
-- =========================================
-- 1. TABLE UTILISATEUR
-- =========================================

CREATE TABLE UTILISATEUR (
    ID_UTILISATEUR NUMBER(10) PRIMARY KEY,
    NOM VARCHAR2(50) NOT NULL,
    PRENOM VARCHAR2(50),
    EMAIL VARCHAR2(100) NOT NULL UNIQUE,
    MOT_DE_PASSE VARCHAR2(255) NOT NULL,
    TELEPHONE VARCHAR2(20),
    ROLE VARCHAR2(20) NOT NULL,
    DATE_CREATION DATE DEFAULT SYSDATE,

    CONSTRAINT CK_USER_ROLE
    CHECK (ROLE IN ('CLIENT', 'RESTAURATEUR'))
);


-- =========================================
-- 2. TABLE RESTAURANT
-- =========================================

CREATE TABLE RESTAURANT (
    ID_RESTAURANT NUMBER(10) PRIMARY KEY,
    NOM VARCHAR2(100) NOT NULL,
    DESCRIPTION VARCHAR2(500),
    ADRESSE VARCHAR2(200) NOT NULL,
    TELEPHONE VARCHAR2(20),
    RATE NUMBER(2),
    CATEGORIE VARCHAR2(200) NOT NULL,
    IMAGEURL VARCHAR2(200) NOT NULL,
    ID_RESTAURATEUR NUMBER(10) NOT NULL,
    
    CONSTRAINT FK_REST_USER
    FOREIGN KEY (ID_RESTAURATEUR)
    REFERENCES UTILISATEUR(ID_UTILISATEUR),

    CONSTRAINT UQ_RESTAURATEUR
    UNIQUE (ID_RESTAURATEUR)
);

-- =========================================
-- 3.TABLE MENU
-- =========================================

CREATE TABLE MENU (
    ID NUMBER(10) PRIMARY KEY,
    NOM VARCHAR2(100) NOT NULL,
    DESCRIPTION VARCHAR2(500),
    PRIX NUMBER(10,3) NOT NULL,
    RESTAURANT_ID NUMBER(10) NOT NULL,
    IMAGE VARCHAR2(255),

    CONSTRAINT FK_MENU_RESTAURANT
    FOREIGN KEY (RESTAURANT_ID)
    REFERENCES RESTAURANT(ID_RESTAURANT)
);

-- =========================================
-- 4. TABLE PRODUIT
-- =========================================

CREATE TABLE PRODUIT (
    ID_PRODUIT NUMBER(10) PRIMARY KEY,
    NOM VARCHAR2(100) NOT NULL,
    DESCRIPTION VARCHAR2(500),
    PRIX NUMBER(10,2) NOT NULL,
    IMAGE VARCHAR2(255),
    ID_MENU NUMBER(10),
    CATEGORIE_P VARCHAR2(100),
    ID_RESTAURANT NUMBER(10) NOT NULL,

    CONSTRAINT CK_PRODUIT_PRIX
    CHECK (PRIX >= 0),

    CONSTRAINT CK_PRODUIT_DISPO
    CHECK (DISPONIBLE IN (0, 1)),
    CONSTRAINT FK_MENU
    FOREIGN KEY ( ID_MENU)
    REFERENCES MENU( ID_MENU)
    CONSTRAINT FK_PROD_CAT
    FOREIGN KEY ( ID_RESTAURANT)
    REFERENCES RESTAURANT( ID_RESTAURANT)
);


-- =========================================
-- 5. TABLE COMMANDE
-- =========================================

CREATE TABLE COMMANDE (
    ID_COMMANDE NUMBER(10) PRIMARY KEY,
    DATE_COMMANDE DATE DEFAULT SYSDATE,
    DATE_RETRAIT DATE,
    HEURE_RETRAIT VARCHAR2(5),
    STATUT VARCHAR2(30) DEFAULT 'RECUE' NOT NULL,
    MODE_RECEPTION VARCHAR2(20) NOT NULL,
    MONTANT_TOTAL NUMBER(10,2) NOT NULL,
    ID_CLIENT NUMBER(10) NOT NULL,
    ID_RESTAURANT NUMBER(10) NOT NULL,

    CONSTRAINT CK_COMMANDE_STATUT
    CHECK (STATUT IN (
        'RECUE',
        'EN_PREPARATION',
        'PRETE',
        'RECUPEREE',
        'ANNULEE'
    )),

    CONSTRAINT CK_MODE_RECEPTION
    CHECK (MODE_RECEPTION IN ('RETRAIT', 'LIVRAISON')),

    CONSTRAINT CK_COMMANDE_MONTANT
    CHECK (MONTANT_TOTAL >= 0),

    CONSTRAINT FK_CMD_CLIENT
    FOREIGN KEY (ID_CLIENT)
    REFERENCES UTILISATEUR(ID_UTILISATEUR),

    CONSTRAINT FK_CMD_REST
    FOREIGN KEY (ID_RESTAURANT)
    REFERENCES RESTAURANT(ID_RESTAURANT)
);


-- =========================================
-- 6. TABLE LIGNE_COMMANDE
-- =========================================

CREATE TABLE LIGNE_COMMANDE (
    ID_LIGNE NUMBER(10) PRIMARY KEY,
    QUANTITE NUMBER(5) NOT NULL,
    PRIX_UNITAIRE NUMBER(10,2) NOT NULL,
    ID_COMMANDE NUMBER(10) NOT NULL,
    ID_PRODUIT NUMBER(10) NOT NULL,

    CONSTRAINT CK_LIGNE_QUANTITE
    CHECK (QUANTITE > 0),

    CONSTRAINT CK_LIGNE_PRIX
    CHECK (PRIX_UNITAIRE >= 0),

    CONSTRAINT FK_LIGNE_CMD
    FOREIGN KEY (ID_COMMANDE)
    REFERENCES COMMANDE(ID_COMMANDE),

    CONSTRAINT FK_LIGNE_PROD
    FOREIGN KEY (ID_PRODUIT)
    REFERENCES PRODUIT(ID_PRODUIT)
);
